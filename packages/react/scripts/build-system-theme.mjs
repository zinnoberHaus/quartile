// Writes src/styles/system-theme.css from tokens.css, so theme="system" follows the reader's
// operating-system preference in plain CSS: correct on the first paint, on the server, and with
// JavaScript disabled. Run after editing color tokens; a unit test fails when the file is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = readFileSync(join(root, 'src/styles/tokens.css'), 'utf8');

export function declarations(css, selector) {
  const start = css.indexOf(selector);
  if (start < 0) throw new Error(`Missing ${selector} in tokens.css`);
  const open = css.indexOf('{', start);
  const close = css.indexOf('\n}', open);
  const body = css.slice(open + 1, close);
  const out = new Map();
  for (const m of body.matchAll(/(--q-[\w-]+)\s*:\s*([^;]+);/g))
    out.set(m[1], m[2].replace(/\s+/g, ' ').trim());
  return out;
}

export function systemTheme(css) {
  const light = declarations(css, ':root,\n[data-theme="light"]');
  const dark = declarations(css, '[data-theme="dark"]');
  const lines = (map) => [...map].map(([k, v]) => `  ${k}: ${v};`).join('\n');
  const lightValues = new Map([...dark.keys()].map((k) => [k, light.get(k)]));
  for (const [k, v] of lightValues) if (v === undefined) throw new Error(`${k} has no light value`);
  return `/* Generated by scripts/build-system-theme.mjs from tokens.css. Do not edit by hand. */
/* theme="system": the reader's color-scheme preference, applied by CSS before any script runs. */
[data-theme="system"] {
  color-scheme: light;
${lines(lightValues)}
}

@media (prefers-color-scheme: dark) {
  [data-theme="system"] {
    color-scheme: dark;
${lines(dark).replace(/^ {2}/gm, '    ')}
  }
}
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(join(root, 'src/styles/system-theme.css'), systemTheme(tokens));
  console.log('system-theme.css written');
}
